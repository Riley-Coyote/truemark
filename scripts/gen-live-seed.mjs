import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
export const seedFile = new URL('supabase/migrations/20261001000100_seed.sql', root);

// Read only the two literal arrays. Importing seed.ts would also execute the
// fictional people/order generator; no preview records belong in the live seed.
async function literalArray(relativePath, name) {
  const source = ts.createSourceFile(relativePath, await readFile(new URL(relativePath, root), 'utf8'), ts.ScriptTarget.Latest, true);
  const declaration = source.statements
    .filter(ts.isVariableStatement)
    .flatMap((statement) => [...statement.declarationList.declarations])
    .find((entry) => ts.isIdentifier(entry.name) && entry.name.text === name);
  assert(declaration?.initializer, `Missing ${name} in ${relativePath}`);
  function literal(node) {
    if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal);
    if (ts.isObjectLiteralExpression(node)) {
      return Object.fromEntries(node.properties.map((property) => {
        assert(ts.isPropertyAssignment(property), `${name}: only literal properties are supported`);
        assert(ts.isIdentifier(property.name) || ts.isStringLiteral(property.name));
        return [property.name.text, literal(property.initializer)];
      }));
    }
    if (ts.isStringLiteral(node)) return node.text;
    if (ts.isNumericLiteral(node)) return Number(node.text);
    if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
    if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
    if (node.kind === ts.SyntaxKind.NullKeyword) return null;
    throw new Error(`${name}: unsupported expression ${node.getText(source)}`);
  }
  const result = literal(declaration.initializer);
  assert(Array.isArray(result) && result.length > 0);
  return result;
}

export async function readSeedData() {
  const [products, shippingMethods] = await Promise.all([
    literalArray('src/data.ts', 'products'),
    literalArray('src/platform/seed.ts', 'shippingMethods'),
  ]);
  for (const rows of [products, shippingMethods]) {
    assert.equal(new Set(rows.map((row) => row.id)).size, rows.length, 'Duplicate seed id');
    for (const row of rows) {
      assert(/^[a-z0-9-]+$/.test(row.id));
      assert(Number.isFinite(row.price) && row.price >= 0, `Missing price for ${row.id}`);
      assert(Math.abs(row.price * 100 - Math.round(row.price * 100)) < 1e-8, 'Prices must be cents');
    }
  }
  assert.equal(new Set(products.map((product) => product.lot)).size, products.length);
  for (const product of products) assert(/^TM-[A-Z0-9-]+$/.test(product.lot), 'Only real first-batch lot identifiers');
  return { products, shippingMethods };
}

function sql(value) {
  if (value === undefined || value === null) return 'null';
  if (typeof value === 'number') {
    assert(Number.isFinite(value));
    return String(value);
  }
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  return `'${String(value).replaceAll("'", "''")}'`;
}

export function renderSeed({ products, shippingMethods }) {
  const values = (rows) => rows.map((row) => `  (${row.map(sql).join(', ')})`).join(',\n');
  return `-- Generated by node scripts/gen-live-seed.mjs. Do not edit by hand.
-- Sources: src/data.ts products; src/platform/seed.ts shippingMethods.
-- Insert missing records only: reruns preserve the client's prices, releases,
-- inventory and promo decisions. No fictional people, orders, partners or results.
begin;
set local standard_conforming_strings = on;

insert into public.products (id, name, size, category, price, image, color, color_ink, form, lot, tag, active) values
${values(products.map((p) => [p.id, p.name, p.size, p.category, p.price, p.image, p.color, p.colorInk, p.form, p.lot, p.tag, true]))}
on conflict (id) do nothing;

-- Only the identifiers are established facts. Dates and stock counts in the
-- preview are generated, so received_at and units deliberately remain null.
insert into public.lots (lot, product_id, status, results) values
${values(products.map((p) => [p.lot, p.id, 'testing', '[]']))}
on conflict (lot) do nothing;

insert into public.shipping_methods (id, label, detail, price, active) values
${values(shippingMethods.map((m) => [m.id, m.label, m.detail, m.price, true]))}
on conflict (id) do nothing;

-- Sample offer percentages are retained but disabled until the client decides.
insert into public.discounts (code, kind, percent, active) values
  ('FIRSTLOT', 'promo', 10, false),
  ('WELCOME5', 'promo', 5, false)
on conflict (code) do nothing;

commit;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const data = await readSeedData();
  await writeFile(seedFile, renderSeed(data));
  console.log(`Generated ${fileURLToPath(seedFile)} (${data.products.length} products/lots, ${data.shippingMethods.length} shipping methods, 2 inactive promos)`);
}
