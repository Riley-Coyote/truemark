/** Real local Auth/REST/functions acceptance. Creates synthetic orders only. */
import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';
import { createLiveAdapter } from '../src/platform/live/adapter.ts';
import { status, password, flush, stateDir } from './lib/local-platform.mjs';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const config=status(), checks=[];
async function actor(email) {
  const client=createClient(config.API_URL,config.ANON_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
  const login=await client.auth.signInWithPassword({email,password});
  if(login.error)throw login.error;
  return createLiveAdapter(client);
}
let buyer=await actor('researcher@truemark.test');
const owner=await actor('owner@truemark.test'),partner=await actor('partner@truemark.test'),pending=await actor('pending@truemark.test');
function pass(name){checks.push(name);console.log('PASS '+name);}
assert.equal((await owner.auth.profile()).role,'owner');
assert.equal((await buyer.auth.profile()).role,'buyer');
let me=await buyer.store.session.get();
const catalog=await buyer.store.catalog.products();
const product=catalog.find(p=>p.id==='bpc-157-10-mg');
assert(product&&product.stock>=4);
await assert.rejects(()=>buyer.store.catalog.saveProduct({...product,stock:999999}),/Team|access|permission/i);
pass('real role-based sign-in and rejected customer catalog writes');
const draft={lines:[{productId:product.id,quantity:2}],address:me.addresses[0],shipping:'cold-2day',discountCode:'ALEX10'};
await assert.rejects(()=>pending.store.orders.place('ignored',draft),/verif|approv/i);
pass('pending research accounts cannot purchase');
const admin=createClient(config.API_URL,config.SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const email='acceptance-'+Date.now()+'@truemark.test';
const created=await admin.auth.admin.createUser({email,password,email_confirm:true,user_metadata:{application:{name:'Local acceptance researcher',institution:'Local test laboratory',role:'Research scientist',institutionType:'Laboratory',researchArea:'Analytical research',intendedUse:'In vitro research',attestations:[],documents:[]}}});
if(created.error)throw created.error;
const application=(await owner.store.applications.list()).find(a=>a.email===email);
assert(application);
await owner.store.applications.review(application.id,'approved','Local acceptance verification');
buyer=await actor(email);me=await buyer.store.session.get();draft.address=me.addresses[0]??draft.address;
assert.equal(me.status,'verified');
pass('new application approved through the real owner operation');
const beforePartner=await partner.store.partners.me();
const order=await buyer.store.orders.place(me.id,draft);
const reserved=(await buyer.store.catalog.products()).find(p=>p.id===product.id).stock;
assert.equal(reserved,product.stock-2);
assert.equal((await buyer.payments.pay(order.id,'approve')).status,'succeeded');
assert.equal((await owner.store.orders.get(order.id)).status,'paid');
assert((await partner.store.partners.referrals(beforePartner.id)).some(r=>r.orderId===order.id));
pass('checkout, stock reservation, signed payment callback and partner commission');
await flush(config);
assert.equal((await owner.shipping.get(order.id)).status,'pushed');
await owner.shipping.simulate(order.id,'label');
assert.equal((await owner.store.orders.get(order.id)).status,'paid');
assert((await owner.shipping.get(order.id)).labelCreatedAt);
await owner.store.orders.advance(order.id,'packed');
await owner.shipping.simulate(order.id,'shipped');
await owner.shipping.simulate(order.id,'delivered');
assert.equal((await buyer.store.orders.get(order.id)).status,'delivered');
pass('label remains distinct from packing, shipment and delivery');
await flush(config);
const outbox=await owner.messages.outbox(order.id);
assert(outbox.some(m=>m.status==='sent'&&m.provider==='simulator'));
pass('rendered order notifications recorded by the simulated delivery worker');
await owner.payments.refund(order.id,order.total,'Local acceptance test refund');
assert.equal((await buyer.store.orders.get(order.id)).payment,'refunded');
assert.equal((await buyer.store.catalog.products()).find(p=>p.id===product.id).stock,reserved);
assert.equal((await partner.store.partners.referrals(beforePartner.id)).find(r=>r.orderId===order.id).status,'void');
pass('refund, commission reversal and no assumed physical stock return');
const declined=await buyer.store.orders.place(me.id,{...draft,lines:[{productId:product.id,quantity:1}]});
assert.equal((await buyer.payments.pay(declined.id,'decline')).status,'failed');
await buyer.payments.cancelUnpaid(declined.id);
assert.equal((await buyer.store.catalog.products()).find(p=>p.id===product.id).stock,reserved);
pass('declined payment and cancellation return reserved stock');
const routes=await owner.messages.routes();
await buyer.messages.sendContact({topic:routes[0].topic,name:me.name,email:me.email,organization:me.institution,message:'Local functional acceptance enquiry.',website:''});
assert((await owner.messages.contacts()).some(m=>m.message==='Local functional acceptance enquiry.'));
pass('customer contact form reaches the Command Center inbox');
const categories=await owner.store.catalog.categories();
const saved=await owner.store.catalog.saveProduct({...product,stock:reserved,description:product.description??null},reserved);
assert.equal(saved.stock,reserved);assert(categories.length>0);
pass('catalog edits persist through the actual checked save operation');
await writeFile(resolve(stateDir,'verification.json'),JSON.stringify({at:new Date().toISOString(),order:order.number,orderId:order.id,checks},null,2)+'\n');
console.log('Verified local order '+order.number+'. Report: .local-platform/verification.json');
process.exit(0);
