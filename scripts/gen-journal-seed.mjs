import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
export const contentFile = new URL('supabase/migrations/20261001000400_content.sql', root);
const begin = '-- BEGIN GENERATED JOURNAL SEED';
const end = '-- END GENERATED JOURNAL SEED';
// These two modules are pure source data/conversion, with no runtime imports.
async function moduleAt(file) {
  const source = await readFile(new URL(file, root), 'utf8');
  const { outputText } = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
}
export async function readJournalSeed() {
  const [{ articles, categoryLabel }, { articleMarkdown }] = await Promise.all([
    moduleAt('src/brand/articles.ts'), moduleAt('src/brand/markdown-source.ts'),
  ]);
  assert.equal(articles.length, 7, 'Expected the seven client articles');
  return articles.map((article) => ({
    slug: article.id, title: article.title, kicker: categoryLabel(article.category), excerpt: article.dek,
    body_md: articleMarkdown(article.body), cover_image: `images/scenes/${article.image.scene}.webp`,
    reading_minutes: Number.parseInt(article.readTime, 10), status: 'published',
    published_at: `${article.iso}T00:00:00Z`, author: article.author,
  }));
}
const sql = (value) => typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
export function renderJournalSeed(articles) {
  const fields = Object.keys(articles[0]);
  return `${begin}\n-- Generated by node scripts/gen-journal-seed.mjs from src/brand/articles.ts.\n-- Seed once; reruns preserve edits, drafts and deletions.\ndo $journal_seed$ begin\nif current_setting('platform.wp16_seed') = 'true' then\ninsert into public.articles (${fields.join(', ')}) values\n${articles.map((article) => `  (${fields.map((field) => sql(article[field])).join(', ')})`).join(',\n')}\non conflict (slug) do nothing;\nend if;\nend $journal_seed$;\n${end}`;
}
export function replaceJournalSeed(source, articles) {
  assert(source.includes(begin) && source.includes(end), 'Missing seed markers');
  return source.slice(0, source.indexOf(begin)) + renderJournalSeed(articles) + source.slice(source.indexOf(end) + end.length);
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const articles = await readJournalSeed();
  await writeFile(contentFile, replaceJournalSeed(await readFile(contentFile, 'utf8'), articles));
  console.log(`Generated ${articles.length} client articles in ${fileURLToPath(contentFile)}`);
}
