// Bundles each server function and its `_shared` imports into one file, for
// projects deployed by pasting into Supabase's dashboard editor instead of the CLI.
// Run: node scripts/bundle-functions.mjs [name ...]   → dist-functions/<name>/index.ts
import { build } from 'esbuild';
import { readdir, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const functions = join(root, 'supabase', 'functions');
const requested = process.argv.slice(2);
const names = requested.length ? requested : (await readdir(functions)).filter((name) => !name.startsWith('_') && !name.startsWith('.'));
for (const name of names) {
  const entry = join(functions, name, 'index.ts');
  await stat(entry);
  const outfile = join(root, 'dist-functions', name, 'index.ts');
  await build({
    entryPoints: [entry], outfile, bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
    legalComments: 'none', logLevel: 'warning',
    banner: { js: `// Generated by scripts/bundle-functions.mjs from supabase/functions/${name}. Do not edit; rebuild.` },
  });
  console.log(`bundled ${name} → ${outfile}`);
}
